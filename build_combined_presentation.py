#!/usr/bin/env python3
"""
Combines rsfMRI_processing_summary_with_anat_appendix.pptx (39 slides -- the
session review + appendix) and Data_Analysis_Scripts_Overview.pptx (25
slides -- how the scripts work) into one sequential deck: a new title +
master contents, then each source deck's own content (minus its own
title/contents slides, which the new combined title/contents replace),
separated by a "PART" divider.

python-pptx has no built-in cross-presentation "copy slide" API, so this
copies each source slide's shape XML (copy_slide()) into a freshly-added
blank slide in the new presentation, including background fill and any
embedded images (re-relating each picture's blob into the destination
package and rewriting its r:embed rId -- otherwise copied <a:blip> elements
would point at relationship IDs that don't exist in the new file).

A final pass (renumber_and_fix_references) then renumbers every page-number
badge to its true combined-deck position and remaps the slide-number
references named in the rsfMRI appendix's own index slides, so the result
reads as one continuous document rather than decks stitched together.

Also appends a "PART III -- Data Statistics" section at the end: 4 pre-made
figures (scan_sessions_5groups.png, age_range_boxplot_5groups.png,
interval_summary_table.png, interval_summary_rangeplot.png) covering the
broader HCP-Aging AABC cohort's scan-session counts, age distributions, and
inter-visit intervals -- not generated by any script in this folder, just
placed in the project root and embedded here in the order given.

Standard command:
  python3 build_combined_presentation.py

Output:
  Combined_rsfMRI_and_Scripts_Overview.pptx (project root, one directory up
  from this scripts folder)
"""
