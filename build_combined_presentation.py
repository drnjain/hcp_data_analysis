def set_solid_bg(slide, color):
    slide.background.fill.solid()
    slide.background.fill.fore_color.rgb = color


def add_textbox(slide, left, top, width, height, text, size, color, bold=False,
                 font="Calibri", align=PP_ALIGN.LEFT):
    box = slide.shapes.add_textbox(left, top, width, height)
    tf = box.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    lines = text.split("\n")
    for i, line in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        run = p.add_run()
        run.text = line
        run.font.name = font
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.color.rgb = color
    return box


def copy_slide(dest_prs, src_slide, dest_layout):
    """Deep-copy src_slide's background + every shape into a new slide of
    dest_prs, re-relating any embedded images into the destination package."""
    dest_slide = dest_prs.slides.add_slide(dest_layout)

    for shp in list(dest_slide.shapes):
        shp._element.getparent().remove(shp._element)

    src_cSld = src_slide._element.find(qn("p:cSld"))
    dest_cSld = dest_slide._element.find(qn("p:cSld"))
    src_bg = src_cSld.find(qn("p:bg"))
    dest_bg = dest_cSld.find(qn("p:bg"))
    if dest_bg is not None:
        dest_cSld.remove(dest_bg)
    if src_bg is not None:
        dest_cSld.insert(0, copy.deepcopy(src_bg))

    src_spTree = src_slide.shapes._spTree
    dest_spTree = dest_slide.shapes._spTree
    skip_tags = {qn("p:nvGrpSpPr"), qn("p:grpSpPr")}
    for elem in list(src_spTree):
        if elem.tag in skip_tags:
            continue
        new_elem = copy.deepcopy(elem)
        for blip in new_elem.iter(qn("a:blip")):
            r_embed = blip.get(qn("r:embed"))
            if r_embed:
                image_part = src_slide.part.related_part(r_embed)
                _new_part, new_rid = dest_slide.part.get_or_add_image_part(
                    io.BytesIO(image_part.blob)
                )
                blip.set(qn("r:embed"), new_rid)
        dest_spTree.append(new_elem)

    return dest_slide


