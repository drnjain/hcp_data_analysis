# ---- Final pass: every copied slide keeps its ORIGINAL deck's own page-number
# badge and (for two rsfMRI appendix dividers) body text that references slide
# numbers by name -- both need remapping to the combined deck's actual 1-63
# positions so the merged deck reads as one continuous document, not two
# decks stitched together.
BADGE_POSITIONS = {(11277295, 146304), (11094415, 6492240), (502920, 6492240)}


def fix_page_badges(dest):
    for i, slide in enumerate(dest.slides, start=1):
        for sh in slide.shapes:
            if not sh.has_text_frame:
                continue
            txt = sh.text_frame.text.strip()
            if not txt.isdigit():
                continue
            if (sh.left, sh.top) not in BADGE_POSITIONS:
                continue
            # Scripts-deck section dividers put their (only) badge bottom-left;
            # move it to the same bottom-right spot every other slide uses.
            if (sh.left, sh.top) == (502920, 6492240):
                sh.left = Emu(11094415)
            run = sh.text_frame.paragraphs[0].runs[0]
            run.text = str(i).zfill(len(txt)) if txt.startswith("0") else str(i)


# rsfMRI-deck body text already correctly names ITS OWN (post-divider-insertion,
# 38-slide) slide numbers after fix_stale_slide_references.py -- within the
# combined deck those slides sit at local_number + 1 (title+contents+PartI
# divider precede them, minus the 2 slides of its own title+contents skipped).
RSFMRI_TEXT_REMAP = {
    # "(Slide 5)"/"see Slide 5" were already fixed to say "Slide 8" locally
    # by fix_stale_slide_references.py -> +1 for the combined deck = 9
    "Slide 8": "Slide 9",
    "slides 8 and 10": "slides 9 and 11",
    "Slide 22": "Slide 23", "Slide 23": "Slide 24",
    "Slides 25–33": "Slides 26–34", "Slides 35–38": "Slides 36–39",
    "Slide 25": "Slide 26", "Slide 26": "Slide 27", "Slide 27": "Slide 28",
    "Slides 28–30": "Slides 29–31", "Slides 31–32": "Slides 32–33", "Slide 33": "Slide 34",
    "Slide 35": "Slide 36", "Slide 36": "Slide 37", "Slide 37": "Slide 38", "Slide 38": "Slide 39",
    "Slide 39": "Slide 40",
}
# Single-pass regex: the original text is scanned once and every match is
# replaced via lookup -- critical, since sequential str.replace() calls over
# this dict would cascade (a "Slide 25"->"Slide 26" replacement would then
# get caught -- and wrongly re-replaced -- by the "Slide 26"->"Slide 27" rule).
_RSFMRI_PATTERN = re.compile(
    "|".join(re.escape(k) for k in sorted(RSFMRI_TEXT_REMAP, key=len, reverse=True))
)


def fix_index_text(dest):
    # Part I content occupies combined slides 4-40 (rsfMRI's own local 3-39 + 1)
    for slide in list(dest.slides)[3:40]:
        for sh in slide.shapes:
            if not sh.has_text_frame:
                continue
            for para in sh.text_frame.paragraphs:
                for run in para.runs:
                    if _RSFMRI_PATTERN.search(run.text):
                        run.text = _RSFMRI_PATTERN.sub(lambda m: RSFMRI_TEXT_REMAP[m.group(0)], run.text)


def renumber_and_fix_references(dest):
    fix_index_text(dest)
    fix_page_badges(dest)


if __name__ == "__main__":
    build()
